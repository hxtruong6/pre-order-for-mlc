"""Step 8 of the runtime-scaling benchmark (reviewer 1 response).

Generate FOUR pgfplots/TikZ figures (copy-paste ready for LaTeX):

    {pre-order, partial-order} x {Hamming, Subset}

Each figure has:
  * the four main solver curves (GLPK / HiGHS x full / height=2),
  * one dashed power-law TREND line per curve, labelled with its fitted
    exponent K^x (drawn across the full K range so GLPK's trend is visible
    even where it is too slow to measure),
  * horizontal baseline lines (BR, CC, CLR, ECC),
  * axis labelled in K (paper notation), log-log, NO interior grid.

Writes each figure as a standalone .tex (the inner tikzpicture is what you
paste into the paper) and, if a LaTeX toolchain is present, compiles a .pdf +
.png preview.
"""

